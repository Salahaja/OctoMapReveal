"""Writes OctoMapReveal/Overlays.lua from the client's WorldMapOverlay.dbc and
WorldMapArea.dbc (dumped by dbcdump.js). Re-run after any client patch:

  set ELECTRON_RUN_AS_NODE=1
  electron tools/dbcdump.js "<client>/Data" WorldMapOverlay > WorldMapOverlay.json
  electron tools/dbcdump.js "<client>/Data" WorldMapArea > WorldMapArea.json
  python tools/build.py

Entries use the ShaguTweaks/pfUI hash format NAME:width:height:offsetX:offsetY,
keep the client's spelling (the reveal modules match explored overlays by exact
texture path) and the DBC's order (later overlays draw on top)."""
import datetime
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
# WorldMapOverlay.dbc (1.12): id, area, areatable x4, mappoint x2, texture,
# width, height, offsetX, offsetY, hitrect x4
ov = json.load(open(os.path.join(ROOT, "WorldMapOverlay.json")))
wa = json.load(open(os.path.join(ROOT, "WorldMapArea.json")))
assert ov["fields"] == 17 and wa["fields"] == 8, "unexpected DBC layout"
areas = {r[0]: wa["str"].get(str(r[3]), "") for r in wa["rows"]}

maps = {}
for r in ov["rows"]:
    tex = ov["str"].get(str(r[8]), "")
    if not tex:
        continue
    w, h, x, y = r[9:13]
    e = "%s:%d:%d:%d:%d" % (tex, w, h, x, y)
    if r[6] or r[7]:
        e += ":%d:%d" % (r[6], r[7])
    maps.setdefault(areas[r[1]], []).append(e)

out = ["-- Generated by tools/build.py from the client's WorldMapOverlay.dbc",
       "-- (%s, %d overlays on %d maps, %s). Do not edit by hand." % (
           ov["from"], sum(map(len, maps.values())), len(maps), datetime.date.today().isoformat()),
       "OctoMapReveal_Overlays = {"]
for name in sorted(maps):
    out.append('  ["%s"] = {%s},' % (name, ", ".join('"%s"' % e for e in maps[name])))
out.append("}")
dest = os.path.join(ROOT, "OctoMapReveal", "Overlays.lua")
os.makedirs(os.path.dirname(dest), exist_ok=True)
open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote %s: %d maps, %d overlays" % (dest, len(maps), sum(map(len, maps.values()))))
